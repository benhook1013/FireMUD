    def extract_hcl_block(text, header):
        """Extract one exact top-level HCL block without consuming following blocks."""
        match = re.search(rf'(?m)^{re.escape(header)}\s*\{{', text)
        if match is None:
            return None
        opening_brace = text.find("{", match.start(), match.end())
        depth = 0
        in_string = False
        escaped = False
        line_comment = False
        block_comment = False
        for index in range(opening_brace, len(text)):
            char = text[index]
            next_char = text[index + 1] if index + 1 < len(text) else ""
            if line_comment:
                if char == "\n":
                    line_comment = False
            elif block_comment:
                if char == "*" and next_char == "/":
                    block_comment = False
            elif in_string:
                if escaped:
                    escaped = False
                elif char == "\\":
                    escaped = True
                elif char == '"':
                    in_string = False
            elif char == '"':
                in_string = True
            elif char == "#" or (char == "/" and next_char == "/"):
                line_comment = True
            elif char == "/" and next_char == "*":
                block_comment = True
            elif char == "{":
                depth += 1
            elif char == "}":
                depth -= 1
                if depth == 0:
                    return text[match.start() : index + 1]
        return None

