#!/usr/bin/env python3
"""Validate canonical workflow tool and runtime authorities."""

from __future__ import annotations

import json
import os
import re
import subprocess
import tempfile
from collections import Counter
from pathlib import Path

import yaml


def main() -> int:
    root = Path(os.environ.get("FIREMUD_REPO_ROOT", Path(__file__).resolve().parents[2]))
    workflows = root / ".github/workflows"
    actions = root / ".github/actions"

    def fail(m):
        raise SystemExit(m)

    def authority(path):
        out = {}
        for line in path.read_text().splitlines():
            if not line or line.startswith("#"):
                continue
            if not re.fullmatch(r"[A-Z][A-Z0-9_]*=[A-Za-z0-9._:-]+", line):
                fail(f"{path}: invalid authority line: {line}")
            k, v = line.split("=", 1)
            if k in out:
                fail(f"{path}: duplicate {k}")
            out[k] = v
        return out

    node = (root / ".node-version").read_text().strip()
    if not re.fullmatch(r"24\.\d+\.\d+", node):
        fail(".node-version must pin an exact Node 24 release")
    python = (root / ".python-version").read_text().strip()
    if not re.fullmatch(r"3\.14\.\d+", python):
        fail(".python-version must pin an exact Python 3.14 release")
    requirements_profiles = {
        "yaml": root / "config/python/yaml-requirements.txt",
        "ci": root / "config/python/ci-requirements.txt",
        "smoke": root / "config/python/smoke-requirements.txt",
        "docs": root / "config/docs/requirements.txt",
    }
    requirements_inputs = {
        "yaml": root / "config/python/yaml-requirements.in",
        "ci": root / "config/python/ci-requirements.in",
        "smoke": root / "config/python/smoke-requirements.in",
    }
    expected_lock_header = f"# This file is autogenerated by pip-compile with Python {'.'.join(python.split('.')[:2])}"
    for path in requirements_profiles.values():
        if expected_lock_header not in path.read_text().splitlines()[:8]:
            fail(f"{path} must be generated with Python {python}")
    expected_compile_commands = {
        "yaml": "--output-file=config/python/yaml-requirements.txt config/python/yaml-requirements.in",
        "ci": "--output-file=config/python/ci-requirements.txt config/python/ci-requirements.in",
        "smoke": "--output-file=config/python/smoke-requirements.txt config/python/smoke-requirements.in",
    }
    expected_direct_requirements = {
        "yaml": {"pyyaml"},
        "ci": {"pathspec", "ruff", "yamllint"},
        "smoke": {"websocket-client"},
    }
    for name, path in requirements_inputs.items():
        if not path.is_file() or not path.read_text().strip():
            fail(f"{path} must define unlocked direct requirements")
        direct_requirements = {
            line.strip().lower()
            for line in path.read_text().splitlines()
            if line.strip() and not line.lstrip().startswith("#") and not line.startswith("-r ")
        }
        input_includes = [line.strip() for line in path.read_text().splitlines() if line.strip().startswith("-r ")]
        if input_includes != (["-r yaml-requirements.in"] if name == "ci" else []):
            fail(f"{path} must use the canonical YAML input relationship")
        if direct_requirements != expected_direct_requirements[name]:
            fail(f"{path} does not match its canonical direct dependencies")
        lock_text = requirements_profiles[name].read_text()
        if not any(expected_compile_commands[name] in line for line in lock_text.splitlines()[:8]):
            fail(f"{requirements_profiles[name]} must record regeneration from {path.name}")
    requirement_line = re.compile(r"(?i)^([a-z0-9][a-z0-9_.-]*)==([^=\s\\]+)\s*\\?$")
    hash_line = re.compile(r"^--hash=sha256:[0-9a-f]{64}\s*\\?$")

    def read_lock(path):
        entries = {}
        current = None
        includes = []
        for raw in path.read_text().splitlines():
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            if line.startswith("-r "):
                includes.append(line[3:])
                continue
            match = requirement_line.fullmatch(line)
            if match:
                current = match.group(1).lower()
                if current in entries:
                    fail(f"{path}: duplicate pinned dependency: {current}")
                entries[current] = [match.group(2), 0]
                continue
            if hash_line.fullmatch(line):
                if current is None:
                    fail(f"{path}: hash is not attached to a pinned dependency")
                entries[current][1] += 1
                continue
            fail(f"{path}: invalid hashed lock line: {raw}")
        if not entries:
            fail(f"{path} must contain at least one pinned dependency")
        missing = [name for name, (version, hashes) in entries.items() if hashes == 0]
        if missing:
            fail(f"{path}: dependencies lack hashes: {', '.join(sorted(missing))}")
        return entries, includes

    locks = {name: read_lock(path) for name, path in requirements_profiles.items()}
    for name, (entries, includes) in locks.items():
        if includes:
            fail(f"{name} requirements must not include another profile")
    for dependency, (version, _) in locks["yaml"][0].items():
        if locks["ci"][0].get(dependency, (None,))[0] != version:
            fail(f"ci requirements must resolve the canonical YAML dependency: {dependency}")

    ap = root / "config/workflow-tool-versions.env"
    a = authority(ap)
    versions = ["KUBECTL", "HELM", "GH", "BUF", "KUBECONFORM", "VELERO", "ACTIONLINT", "TRIVY", "LYCHEE", "ORT", "ZAP"]
    if any(not re.fullmatch(r"\d+\.\d+\.\d+", a.get(f"{x}_VERSION", "")) for x in versions):
        fail("all workflow tools must have exact versions")
    if not re.fullmatch(r"\d+\.\d+\.\d+", a.get("VELERO_CHART_VERSION", "")):
        fail("Velero chart authority must have an exact three-part version")
    pairs = {
        "KUBECTL": "KUBECTL_LINUX_AMD64",
        "HELM": "HELM_LINUX_AMD64",
        "GH": "GH_LINUX_AMD64",
        "BUF": "BUF_LINUX_X86_64",
        "KUBECONFORM": "KUBECONFORM_LINUX_AMD64",
        "VELERO": "VELERO_LINUX_AMD64",
        "TRIVY": "TRIVY_LINUX_AMD64",
        "LYCHEE": "LYCHEE_LINUX_X86_64_MUSL",
    }
    for tool, stem in pairs.items():
        if a.get(f"{stem}_CHECKSUM_VERSION") != a[f"{tool}_VERSION"]:
            fail(f"{tool} checksum version is stale")
        if not re.fullmatch(r"[0-9a-f]{64}", a.get(f"{stem}_SHA256", "")):
            fail(f"{tool} checksum is invalid")
    for tool in ("VELERO_IMAGE", "ORT", "ZAP"):
        if not re.fullmatch(r"sha256:[0-9a-f]{64}", a.get(f"{tool}_DIGEST", "")):
            fail(f"{tool} digest is invalid")
    expected = (
        {f"{x}_VERSION" for x in versions}
        | {f"{s}_{suffix}" for s in pairs.values() for suffix in ("CHECKSUM_VERSION", "SHA256")}
        | {"VELERO_CHART_VERSION", "VELERO_IMAGE_DIGEST", "ORT_DIGEST", "ZAP_DIGEST"}
    )
    if set(a) != expected:
        fail("workflow tool authority has unexpected or missing keys")

    loader = yaml.safe_load((actions / "load-workflow-tool-versions/action.yml").read_text())
    loader_runs = [
        step.get("run")
        for step in loader.get("runs", {}).get("steps", [])
        if isinstance(step, dict) and isinstance(step.get("run"), str)
    ]
    if len(loader_runs) != 1:
        fail("workflow authority loader must define exactly one validation script")
    loader_run = loader_runs[0]
    expected_loader_outputs = {
        "kubectl-version",
        "kubectl-linux-amd64-sha256",
        "helm-version",
        "helm-linux-amd64-sha256",
        "gh-version",
        "gh-linux-amd64-sha256",
        "buf-version",
        "buf-linux-x86-64-sha256",
        "kubeconform-version",
        "kubeconform-linux-amd64-sha256",
        "velero-version",
        "velero-linux-amd64-sha256",
        "actionlint-version",
        "trivy-version",
        "trivy-linux-amd64-sha256",
        "lychee-version",
        "lychee-linux-x86-64-musl-sha256",
        "ort-image",
        "zap-image",
    }
    if set(loader.get("outputs", {})) != expected_loader_outputs:
        fail("workflow authority loader outputs are unexpected or incomplete")
    for output in expected_loader_outputs:
        output_definition = loader["outputs"][output]
        if not isinstance(output_definition, dict) or not isinstance(output_definition.get("description"), str):
            fail(f"workflow authority loader output is missing a description: {output}")
        if not output_definition["description"].strip():
            fail(f"workflow authority loader output description is empty: {output}")
        value = output_definition.get("value") if isinstance(output_definition, dict) else None
        if value != "${{ steps.versions.outputs." + output + " }}":
            fail(f"workflow authority loader output is not sourced from validation: {output}")
    with tempfile.TemporaryDirectory() as temporary:
        workspace = Path(temporary) / "workspace"
        workspace.mkdir()
        authority_path = workspace / "config"
        authority_path.mkdir()
        output_path = Path(temporary) / "github-output"
        output_path.write_text("sentinel\n")
        env = {**os.environ, "GITHUB_WORKSPACE": str(workspace), "GITHUB_OUTPUT": str(output_path)}
        (authority_path / "workflow-tool-versions.env").write_text(ap.read_text())
        canonical = subprocess.run(
            ["bash", "-c", loader_run], cwd=temporary, env=env, capture_output=True, text=True, check=False
        )
        if canonical.returncode != 0:
            fail(f"workflow authority loader rejects canonical authority: {canonical.stderr.strip()}")
        (authority_path / "workflow-tool-versions.env").write_bytes(
            ap.read_bytes().rstrip(b"\r\n") + b"\nACTIONLINT_VERSION=0.0.0"
        )
        output_path.write_text("sentinel\n")
        eof_duplicate = subprocess.run(
            ["bash", "-c", loader_run], cwd=temporary, env=env, capture_output=True, text=True, check=False
        )
        if eof_duplicate.returncode == 0:
            fail("workflow authority loader accepts a duplicate final line without a newline")
        if output_path.read_text() != "sentinel\n":
            fail("duplicate final authority assignment can mutate workflow outputs")
        (authority_path / "workflow-tool-versions.env").write_text(ap.read_text() + " \t  \n# harmless comment\n")
        whitespace = subprocess.run(
            ["bash", "-c", loader_run], cwd=temporary, env=env, capture_output=True, text=True, check=False
        )
        if whitespace.returncode != 0:
            fail(f"workflow authority loader rejects whitespace-only lines: {whitespace.stderr.strip()}")
        (authority_path / "workflow-tool-versions.env").write_text(
            ap.read_text() + "GITHUB_OUTPUT=redirected.output\nnot a key=value\n"
        )
        output_path.write_text("sentinel\n")
        unsupported = subprocess.run(
            ["bash", "-c", loader_run], cwd=temporary, env=env, capture_output=True, text=True, check=False
        )
        if unsupported.returncode == 0:
            fail("workflow authority loader accepts unsupported assignments")
        if output_path.read_text() != "sentinel\n" or (Path(temporary) / "redirected.output").exists():
            fail("unsupported authority assignment can redirect workflow outputs")
        (authority_path / "workflow-tool-versions.env").write_text(ap.read_text() + "KUBECTL_VERSION=0.0.0\n")
        output_path.write_text("sentinel\n")
        duplicate = subprocess.run(
            ["bash", "-c", loader_run], cwd=temporary, env=env, capture_output=True, text=True, check=False
        )
        if duplicate.returncode == 0:
            fail("workflow authority loader accepts duplicate supported assignments")
        if output_path.read_text() != "sentinel\n":
            fail("duplicate supported authority assignment can mutate workflow outputs")
        missing_key_text = "\n".join(
            line for line in ap.read_text().splitlines() if not line.startswith("ACTIONLINT_VERSION=")
        )
        (authority_path / "workflow-tool-versions.env").write_text(missing_key_text + "\n")
        output_path.write_text("sentinel\n")
        missing_key_env = {**env, "ACTIONLINT_VERSION": a["ACTIONLINT_VERSION"]}
        missing_key = subprocess.run(
            ["bash", "-c", loader_run],
            cwd=temporary,
            env=missing_key_env,
            capture_output=True,
            text=True,
            check=False,
        )
        if missing_key.returncode == 0:
            fail("workflow authority loader accepts a missing key supplied by the ambient environment")
        if output_path.read_text() != "sentinel\n":
            fail("missing workflow authority key can mutate workflow outputs")

    def load(path):
        d = yaml.safe_load(path.read_text())
        return d if isinstance(d, dict) else {}

    def run_has_gh(run):
        return bool(re.search(r"(^|[;&|()\s])gh(?:\s|$)", run))

    executable_helper_suffixes = {".cjs", ".js", ".py", ".sh"}

    def is_executable_helper(path):
        if path.suffix in executable_helper_suffixes:
            return True
        try:
            if path.is_file() and path.stat().st_mode & 0o111:
                return True
            with path.open(encoding="utf-8", errors="ignore") as stream:
                return stream.readline().startswith("#!")
        except OSError:
            return False

    def is_executable_file(path):
        try:
            return path.is_file() and bool(path.stat().st_mode & 0o111)
        except OSError:
            return False

    explicit_reference_pattern = re.compile(
        r"(?:^|[;&|()\s])(?:(?:/usr/bin/)?(?:bash|sh|dash|zsh|ksh|python|python3)"
        r"(?:\s+-[A-Za-z0-9][A-Za-z0-9_-]*)*(?:\s+--)?|source|\.)\s+"
        r"(?P<quote>['\"])?(?:(?:\./)|(?:\$ROOT_DIR/)|(?:\$\{ROOT_DIR\}/)|"
        r"(?:\$GITHUB_ACTION_PATH/(?:\.\./)+)|(?:\$\{GITHUB_ACTION_PATH\}/(?:\.\./)+))?"
        r"(?P<path>(?:dev-tools|services)/[A-Za-z0-9_./-]+)"
        r"(?(quote)(?P=quote)|(?![A-Za-z0-9_./'\"-]))",
        flags=re.MULTILINE,
    )

    direct_reference_pattern = re.compile(
        r"(?:^|[;&|()])[ \t]*(?:if[ \t]+)?(?:![ \t]*)?"
        r"(?P<quote>['\"])?(?:(?:\./)|(?:\$ROOT_DIR/)|(?:\$\{ROOT_DIR\}/)|"
        r"(?:\$GITHUB_ACTION_PATH/(?:\.\./)+)|(?:\$\{GITHUB_ACTION_PATH\}/(?:\.\./)+))?"
        r"(?P<path>(?:dev-tools|services)/[A-Za-z0-9_./-]+)"
        r"(?(quote)(?P=quote)|(?![A-Za-z0-9_./'\"-]))",
        flags=re.MULTILINE,
    )

    def explicit_references(text):
        references = {root / match.group("path") for match in explicit_reference_pattern.finditer(text)}
        references.update(
            root / match.group("path")
            for match in direct_reference_pattern.finditer(text)
            if is_executable_file(root / match.group("path"))
        )
        return references

    def references(text):
        explicitly_invoked = explicit_references(text)
        result = set()
        for name in re.findall(r"(?:\./)?((?:dev-tools|services)/[A-Za-z0-9_./-]+)", text):
            path = root / name.rstrip("\"'")
            if path.is_file() and (path in explicitly_invoked or is_executable_helper(path)):
                result.add(path)
        return result

    referenced_file_cache = {}

    def helper_text(text, seen=None):
        seen = set() if seen is None else seen
        parts = [text]
        for path in references(text):
            if path in seen:
                continue
            seen.add(path)
            if path not in referenced_file_cache:
                referenced_file_cache[path] = path.read_text(errors="ignore")
            source = referenced_file_cache[path]
            parts.extend(helper_text(source, seen))
        return parts

    def explicitly_invoked_helper_text(text, seen=None):
        # Dependency profiles follow invoked helpers, not executable-looking paths stored as data.
        seen = set() if seen is None else seen
        parts = [text]
        for path in explicit_references(text):
            if path in seen:
                continue
            seen.add(path)
            if not path.is_file():
                continue
            if path not in referenced_file_cache:
                try:
                    referenced_file_cache[path] = path.read_text(errors="ignore")
                except OSError:
                    continue
            source = referenced_file_cache[path]
            parts.extend(explicitly_invoked_helper_text(source, seen))
        return parts

    workflow_expansion_cache = {}

    def expand_text(text):
        if text not in workflow_expansion_cache:
            workflow_expansion_cache[text] = "\n".join(helper_text(text))
        return workflow_expansion_cache[text]

    conditional_contract_profile = (
        "${{ (needs.changes.outputs.lightweight_only == 'true' && "
        "needs.changes.outputs.design_docs_changed == 'true' && "
        "needs.changes.outputs.validation_python_changed != 'true') && 'yaml' || 'ci' }}"
    )
    ci_branch_expression = "needs.changes.outputs.lightweight_only != 'true'"

    def guarantees_ci_branch(step):
        # The real consumer uses this exact guard; do not infer arbitrary expression semantics here.
        guard = step.get("if")
        if not isinstance(guard, str):
            return False
        expression = guard.strip()
        if expression.startswith("${{") or expression.endswith("}}"):
            if not (expression.startswith("${{") and expression.endswith("}}")):
                return False
            expression = expression[3:-2].strip()
        while expression.startswith("(") and expression.endswith(")"):
            expression = expression[1:-1].strip()
        return expression == ci_branch_expression

    def setup_python_profile(path, step, *, allow_conditional=False):
        with_input = step.get("with", {})
        if not isinstance(with_input, dict):
            fail(f"{path}: setup-python with input must be a mapping")
        profile = with_input.get("requirements", "none")
        valid_profiles = {"yaml", "ci", "smoke", "docs", "none"}
        if allow_conditional:
            valid_profiles.add(conditional_contract_profile)
        if not isinstance(profile, str) or profile not in valid_profiles:
            fail(f"{path}: invalid Python dependency profile")
        return profile

    def composite_python_profile(uses, stack=()):
        if not uses.startswith("./.github/actions/"):
            return None
        action_path = root / uses[2:] / "action.yml"
        if not action_path.is_file():
            return None
        if action_path in stack:
            fail(f"{action_path}: recursive composite Python setup")
        action = yaml.safe_load(action_path.read_text(encoding="utf-8")) or {}
        effective_profile = None
        for step in action.get("runs", {}).get("steps", []):
            if not isinstance(step, dict):
                continue
            step_uses = str(step.get("uses", ""))
            if step_uses == "./.github/actions/setup-python":
                effective_profile = setup_python_profile(action_path, step)
            elif action_path.parent.name == "setup-python" and step_uses.startswith("actions/setup-python@"):
                effective_profile = "none"
            elif step_uses.startswith("./.github/actions/"):
                nested_profile = composite_python_profile(step_uses, (*stack, action_path))
                if nested_profile is not None:
                    effective_profile = nested_profile
        return effective_profile

    for composite in (
        "./.github/actions/download-validated-preview-artifact",
        "./.github/actions/resolve-certificate-identity-mode",
    ):
        if composite_python_profile(composite) != "yaml":
            fail(f"{composite} must expose its canonical YAML Python profile")

    def python_needs(text):
        expanded_text = "\n".join(explicitly_invoked_helper_text(text))
        if not re.search(r"(^|[;&|()\s])(?:/usr/bin/)?python3?(?:\s|$)", expanded_text):
            return None
        if re.search(r"(^|\n)\s*import websocket\b", expanded_text):
            return "smoke"
        if re.search(r"(^|[;&|\s])(ruff|yamllint)(?:\s|$)", expanded_text):
            return "ci"
        if re.search(r"(^|\n)\s*(?:import|from) yaml\b", expanded_text):
            return "yaml"
        if re.search(r"(^|[;&|\s])(?:python3 -m )?mkdocs(?:\s|$)", expanded_text):
            return "docs"
        return "none"

    def has_gh_consumer(expanded_text):
        return run_has_gh(expanded_text)

    def validate_composite_steps(path, steps):
        effective_profile = None
        setup_gh = False
        for step in steps:
            if not isinstance(step, dict):
                continue
            uses = str(step.get("uses", ""))
            run = str(step.get("run", ""))
            expanded_text = expand_text(run)
            need = python_needs(run)
            gh_consumer = has_gh_consumer(expanded_text)
            if uses == "./.github/actions/setup-python":
                effective_profile = setup_python_profile(path, step)
            elif path.parent.name == "setup-python" and uses.startswith("actions/setup-python@"):
                effective_profile = "none"
            elif uses.startswith("./.github/actions/"):
                nested_profile = composite_python_profile(uses)
                if nested_profile is not None:
                    effective_profile = nested_profile
            setup_gh |= uses == "./.github/actions/setup-gh"
            if uses.startswith("actions/setup-python@") and path.parent.name != "setup-python":
                fail(f"{path}: bypasses setup-python wrapper")
            if need is not None:
                if effective_profile is None:
                    fail(f"{path}: Python consumer lacks setup")
                if need != "none":
                    compatible_profiles = {"yaml", "ci"} if need == "yaml" else {need}
                    if effective_profile not in compatible_profiles:
                        fail(f"{path}: Python consumer lacks its pinned dependency profile")
            if gh_consumer and not setup_gh:
                fail(f"{path}: gh consumer lacks setup")

    def validate_workflow_python_steps(path, job_name, steps):
        checkout = False
        py = False
        effective_profile = None
        setup_count = 0
        for step in steps:
            if not isinstance(step, dict):
                continue
            uses = str(step.get("uses", ""))
            run = str(step.get("run", ""))
            if uses.startswith("actions/checkout@"):
                checkout = True
            if uses.startswith("actions/setup-python@"):
                fail(f"{path.name}:{job_name}: bypasses canonical setup-python action")
            if uses == "./.github/actions/setup-python":
                setup_count += 1
                if not checkout:
                    fail(f"{path.name}:{job_name}: Python setup before checkout")
                py = True
                effective_profile = setup_python_profile(
                    f"{path.name}:{job_name}",
                    step,
                    allow_conditional=path.name == "ci.yml" and job_name == "dev-tool-contract-checks",
                )
            elif uses.startswith("./.github/actions/"):
                composite_profile = composite_python_profile(uses)
                if composite_profile is not None:
                    py = True
                    effective_profile = composite_profile
            need = python_needs(run)
            if need is not None and not py:
                fail(f"{path.name}:{job_name}: direct or helper Python consumer uses ambient runner Python")
            if need == "yaml":
                profile_matches = effective_profile in {"yaml", "ci", conditional_contract_profile}
            elif need in {"smoke", "ci", "docs"}:
                profile_matches = effective_profile == need or (
                    effective_profile == conditional_contract_profile and guarantees_ci_branch(step)
                )
            else:
                profile_matches = effective_profile == need
            if need == "yaml" and not profile_matches:
                fail(f"{path.name}:{job_name}: PyYAML helper lacks its pinned dependency profile")
            if need in {"smoke", "ci", "docs"} and not profile_matches:
                fail(f"{path.name}:{job_name}: {need} helper lacks its pinned dependency profile")
        return setup_count

    if python_needs("bash ./dev-tools/tests/dev-tools-readme-contract.sh") == "smoke":
        fail("documentation/data references must not imply the smoke dependency profile")
    if python_needs("bash ./services/game-session-service/websocket-login-look-smoke.sh") != "smoke":
        fail("invoked WebSocket smoke helper must retain the smoke dependency profile")

    with tempfile.TemporaryDirectory(prefix="workflow-authority-", dir=root / "dev-tools") as helper_dir:
        helper_relative = Path(helper_dir).relative_to(root).as_posix()
        ignored = subprocess.run(
            ["git", "check-ignore", "--quiet", "--no-index", "--", f"{helper_relative}/extensionless-helper"],
            cwd=root,
            capture_output=True,
            text=True,
            check=False,
        )
        if ignored.returncode != 0:
            fail("workflow authority fixtures must be ignored under dev-tools")
        helper = Path(helper_dir) / "extensionless-helper"
        shebang_helper = Path(helper_dir) / "shebang-helper"
        suffix_helper = Path(helper_dir) / "other-suffix.bash"
