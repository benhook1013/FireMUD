CREATE TABLE game_session_tenant_scope_reservation (
    game_session_tenant_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_kind VARCHAR(32) NOT NULL,
    reserved_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_gs_tenant_scope_reservation_kind
        UNIQUE (game_session_tenant_id, reservation_kind),
    CONSTRAINT chk_gs_tenant_scope_reservation_positive
        CHECK (game_session_tenant_id > 0),
    CONSTRAINT chk_gs_tenant_scope_reservation_kind
        CHECK (reservation_kind IN ('LEGACY_OCCUPIED', 'FRESH_SOURCE_BOUND'))
);

CREATE TABLE game_session_tenant_canonical_claim (
    target_namespace VARCHAR(63) NOT NULL,
    canonical_tenant_id UUID NOT NULL,
    legacy_game_session_tenant_id BIGINT NOT NULL,
    association_kind VARCHAR(32) NOT NULL,
    reservation_kind VARCHAR(32) NOT NULL,
    association_operation_id UUID NOT NULL,
    association_request_id UUID NOT NULL,
    claimed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_gs_tenant_canonical_claim
        PRIMARY KEY (target_namespace, canonical_tenant_id),
    CONSTRAINT uq_gs_tenant_canonical_claim_private_key
        UNIQUE (target_namespace, legacy_game_session_tenant_id),
    CONSTRAINT uq_gs_tenant_canonical_claim_operation
        UNIQUE (association_operation_id),
    CONSTRAINT uq_gs_tenant_canonical_claim_request
        UNIQUE (target_namespace, association_request_id),
    CONSTRAINT uq_gs_tenant_canonical_claim_association
        UNIQUE (target_namespace, canonical_tenant_id, legacy_game_session_tenant_id,
                association_operation_id, association_kind),
    CONSTRAINT fk_gs_tenant_canonical_claim_reservation
        FOREIGN KEY (legacy_game_session_tenant_id, reservation_kind)
        REFERENCES game_session_tenant_scope_reservation
            (game_session_tenant_id, reservation_kind),
    CONSTRAINT chk_gs_tenant_canonical_claim_namespace CHECK (
        octet_length(target_namespace) BETWEEN 1 AND 63
        AND target_namespace ~ '^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$'
    ),
    CONSTRAINT chk_gs_tenant_canonical_claim_uuid
        CHECK (canonical_tenant_id <> '00000000-0000-0000-0000-000000000000'::UUID),
    CONSTRAINT chk_gs_tenant_canonical_claim_ids CHECK (
        legacy_game_session_tenant_id > 0
        AND association_operation_id <> '00000000-0000-0000-0000-000000000000'::UUID
        AND association_request_id <> '00000000-0000-0000-0000-000000000000'::UUID
    ),
    CONSTRAINT chk_gs_tenant_canonical_claim_kind CHECK (
        (association_kind = 'RETAINED_V8_1' AND reservation_kind = 'LEGACY_OCCUPIED')
        OR
        (association_kind = 'FRESH_SOURCE_BOUND' AND reservation_kind = 'FRESH_SOURCE_BOUND')
    )
);

CREATE TABLE game_session_fresh_tenant_association (
    association_operation_id UUID PRIMARY KEY,
    target_namespace VARCHAR(63) NOT NULL,
    association_request_id UUID NOT NULL,
    source_schema_version INTEGER NOT NULL,
    source_target_namespace VARCHAR(63) NOT NULL,
    source_request_id UUID NOT NULL,
    source_canonical_tenant_id UUID NOT NULL,
    canonical_tenant_id UUID NOT NULL,
    legacy_game_session_tenant_id BIGINT NOT NULL,
    source_game_row_id BIGINT NOT NULL,
    source_game_tenant_key VARCHAR(72) NOT NULL,
    provenance_kind VARCHAR(32) NOT NULL,
    association_kind VARCHAR(32) NOT NULL DEFAULT 'FRESH_SOURCE_BOUND',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_gs_fresh_tenant_association_request
        UNIQUE (target_namespace, association_request_id),
    CONSTRAINT uq_gs_fresh_tenant_association_canonical
        UNIQUE (target_namespace, canonical_tenant_id),
    CONSTRAINT uq_gs_fresh_tenant_association_private_key
        UNIQUE (legacy_game_session_tenant_id),
    CONSTRAINT fk_gs_fresh_tenant_association_reservation
        FOREIGN KEY (legacy_game_session_tenant_id, association_kind)
        REFERENCES game_session_tenant_scope_reservation
            (game_session_tenant_id, reservation_kind),
    CONSTRAINT fk_gs_fresh_tenant_association_claim
        FOREIGN KEY (target_namespace, canonical_tenant_id, legacy_game_session_tenant_id,
                     association_operation_id, association_kind)
        REFERENCES game_session_tenant_canonical_claim
            (target_namespace, canonical_tenant_id, legacy_game_session_tenant_id,
             association_operation_id, association_kind),
    CONSTRAINT chk_gs_fresh_tenant_association_identity CHECK (
        octet_length(target_namespace) BETWEEN 1 AND 63
        AND target_namespace ~ '^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$'
        AND source_target_namespace = target_namespace
        AND source_schema_version = 1
        AND source_request_id = association_request_id
        AND source_canonical_tenant_id = canonical_tenant_id
        AND association_operation_id <> '00000000-0000-0000-0000-000000000000'::UUID
        AND association_request_id <> '00000000-0000-0000-0000-000000000000'::UUID
        AND source_request_id <> '00000000-0000-0000-0000-000000000000'::UUID
        AND canonical_tenant_id <> '00000000-0000-0000-0000-000000000000'::UUID
    ),
    CONSTRAINT chk_gs_fresh_tenant_association_source CHECK (
        legacy_game_session_tenant_id > 0
        AND source_game_row_id > 0
        AND char_length(source_game_tenant_key) BETWEEN 1 AND 72
        AND source_game_tenant_key !~ '^[[:space:]]*$'
        AND provenance_kind = 'NEW_GAME_ROW'
        AND association_kind = 'FRESH_SOURCE_BOUND'
    )
);

