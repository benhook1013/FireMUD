tasks.named<BootRun>("bootRun") {
    val activeProfile =
        System.getProperty("spring.profiles.active") ?: System.getenv("SPRING_PROFILES_ACTIVE")

    if (activeProfile.isNullOrBlank()) {
        systemProperty("spring.profiles.active", "dev")
    }
}

tasks.register<BootRun>("bootRunDevIsolated") {
    group = "application"
    description = "Start the TCP proxy in dev with dev-isolated Telnet handling"
    mainClass.set("net.firedevops.firemud.tcpproxy.TcpProxyServiceApplication")
    classpath = sourceSets.main.get().runtimeClasspath
    systemProperty("spring.profiles.active", "dev")
    environment("TCP_PROXY_DEV_ISOLATED", "true")
}

val generatedDevCertsRelativePath = "build/generated/dev-certs"
val generatedDevCertsResourcePath = "$generatedDevCertsRelativePath/certs"
val effectiveProfile =
    System.getProperty("spring.profiles.active")
        ?: System.getenv("SPRING_PROFILES_ACTIVE")
        ?: "dev"
val autoGenerateDevCerts = effectiveProfile != "prod"
val skipDevCerts = project.hasProperty("skipDevCerts")

sourceSets.main.get().resources.srcDir(generatedDevCertsRelativePath)

val generateTcpProxyDevCerts =
    tasks.register<GenerateTcpProxyDevCertsTask>("generateTcpProxyDevCerts") {
        outputDir.set(layout.buildDirectory.dir(generatedDevCertsResourcePath))
        shouldGenerate.set(autoGenerateDevCerts && !skipDevCerts)
        scriptWorkingDirPath.set(rootProject.projectDir.absolutePath)
    }

tasks.named<ProcessResources>("processResources") {
    dependsOn(generateTcpProxyDevCerts)
    from(generateTcpProxyDevCerts.map { it.outputDir.get().asFile }) {
        into("certs")
    }
    duplicatesStrategy = org.gradle.api.file.DuplicatesStrategy.INCLUDE
}

tasks.withType<BootRun>().configureEach {
    dependsOn(generateTcpProxyDevCerts)
}

tasks.withType<Test>().configureEach {
    dependsOn(generateTcpProxyDevCerts)
}

tasks.register<Test>("crossServiceTest") {
    description = "Runs TELNET/WebSocket cross-service LOOK regression suites."
    useJUnitPlatform()
    include("**/crossservice/**")
    mustRunAfter(tasks.test)
}
